import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";
import {
  CveExceptionError,
  parseCveExceptions,
  renderTrivyIgnore,
} from "../render-trivy-ignore.mjs";

const root = fileURLToPath(new URL("../..", import.meta.url));
const fixtureDir = join(root, "scripts/test/fixtures/cve-exceptions");
const scriptPath = join(root, "scripts/render-trivy-ignore.mjs");
const TODAY = "2026-11-10";

function fixture(name) {
  return readFileSync(join(fixtureDir, name), "utf8");
}

function runCli(args) {
  return spawnSync(process.execPath, [scriptPath, ...args], {
    encoding: "utf8",
  });
}

test("valid fixture renders ignore entries for the scanned image only", () => {
  const records = parseCveExceptions(fixture("valid.yaml"), { today: TODAY });
  assert.equal(records.length, 2);
  assert.equal(records[0].expiry, TODAY);

  const apiIgnore = renderTrivyIgnore(records, "api");
  assert.match(apiIgnore, /^# Generated by scripts\/render-trivy-ignore\.mjs/m);
  assert.match(apiIgnore, /^CVE-2024-10001$/m);
  assert.doesNotMatch(apiIgnore, /CVE-2024-10002/);

  const webIgnore = renderTrivyIgnore(records, "web");
  assert.match(webIgnore, /^CVE-2024-10002$/m);
  assert.doesNotMatch(webIgnore, /CVE-2024-10001/);

  const workerIgnore = renderTrivyIgnore(records, "worker");
  assert.doesNotMatch(workerIgnore, /^CVE-/m);
});

test("expired fixture fails parsing", () => {
  assert.throws(
    () => parseCveExceptions(fixture("expired.yaml"), { today: TODAY }),
    (err) => {
      assert.ok(err instanceof CveExceptionError);
      assert.match(err.message, /expired on 2020-01-01/);
      assert.match(err.message, /CVE-2023-00001/);
      return true;
    },
  );
});

test("missing-field fixture fails parsing", () => {
  assert.throws(
    () => parseCveExceptions(fixture("missing-field.yaml"), { today: TODAY }),
    (err) => {
      assert.ok(err instanceof CveExceptionError);
      assert.match(err.message, /missing field expiry/);
      return true;
    },
  );
});

test("every required field is rejected when it is omitted or blank", () => {
  const fields = ["id", "image", "package", "reason", "expiry", "accepted_by"];
  const base = {
    id: "CVE-2024-10001",
    image: "api",
    package: "libssl3",
    reason: "No fixed package in the pinned Debian snapshot yet.",
    expiry: "2027-01-15",
    accepted_by: "project-owner",
  };
  for (const field of fields) {
    const record = { ...base };
    delete record[field];
    const yaml = [
      "exceptions:",
      ...Object.entries(record).map(([key, value]) =>
        key === Object.keys(record)[0]
          ? `- ${key}: ${value}`
          : `  ${key}: ${value}`,
      ),
      "",
    ].join("\n");
    assert.throws(
      () => parseCveExceptions(yaml, { today: TODAY }),
      (err) => {
        assert.ok(err instanceof CveExceptionError);
        assert.match(err.message, new RegExp(`missing field ${field}`));
        return true;
      },
    );

    const blank = { ...base, [field]: "" };
    const blankYaml = [
      "exceptions:",
      ...Object.entries(blank).map(([key, value], index) => {
        const rendered = value === "" ? `${key}: ""` : `${key}: ${value}`;
        return index === 0 ? `- ${rendered}` : `  ${rendered}`;
      }),
      "",
    ].join("\n");
    assert.throws(
      () => parseCveExceptions(blankYaml, { today: TODAY }),
      (err) => {
        assert.ok(err instanceof CveExceptionError);
        assert.match(err.message, new RegExp(`missing field ${field}`));
        return true;
      },
    );
  }
});

test("wildcard and severity-wide ignores are rejected", () => {
  assert.throws(
    () => parseCveExceptions(fixture("wildcard.yaml"), { today: TODAY }),
    (err) => {
      assert.ok(err instanceof CveExceptionError);
      assert.match(err.message, /wildcard or severity-wide ignore/);
      return true;
    },
  );

  for (const [field, value] of [
    ["id", "*"],
    ["id", "CVE-*"],
    ["image", "all"],
    ["package", "*"],
    ["package", "HIGH"],
  ]) {
    const record = {
      id: "CVE-2024-10001",
      image: "api",
      package: "libssl3",
      reason: "No fixed package in the pinned Debian snapshot yet.",
      expiry: "2027-01-15",
      accepted_by: "project-owner",
      [field]: value,
    };
    const yaml = [
      "exceptions:",
      ...Object.entries(record).map(([key, item], index) => {
        const line = `${key}: ${item}`;
        return index === 0 ? `- ${line}` : `  ${line}`;
      }),
      "",
    ].join("\n");
    assert.throws(
      () => parseCveExceptions(yaml, { today: TODAY }),
      /wildcard or severity-wide ignore/,
    );
  }
});

test("an expired record fails even when another record is still valid", () => {
  const yaml = `
exceptions:
  - id: CVE-2024-10001
    image: api
    package: libssl3
    reason: No fixed package in the pinned Debian snapshot yet.
    expiry: 2027-01-15
    accepted_by: project-owner
  - id: CVE-2020-00001
    image: web
    package: nginx
    reason: This second record is already expired.
    expiry: 2024-01-01
    accepted_by: project-owner
`;
  assert.throws(
    () => parseCveExceptions(yaml, { today: TODAY }),
    /CVE-2020-00001 for web expired/,
  );
});

test("cli writes an ignore file for a valid fixture and fails closed otherwise", () => {
  const dir = mkdtempSync(join(tmpdir(), "trivy-ignore-"));
  try {
    const out = join(dir, ".trivyignore");
    const ok = runCli([
      "--exceptions",
      join(fixtureDir, "valid.yaml"),
      "--image",
      "api",
      "--today",
      TODAY,
      "--out",
      out,
    ]);
    assert.equal(ok.status, 0, ok.stderr);
    const written = readFileSync(out, "utf8");
    assert.match(written, /^CVE-2024-10001$/m);
    assert.doesNotMatch(written, /CVE-2024-10002/);

    const expired = runCli([
      "--exceptions",
      join(fixtureDir, "expired.yaml"),
      "--image",
      "worker",
      "--today",
      TODAY,
    ]);
    assert.equal(expired.status, 1);
    assert.match(expired.stderr, /expired/);

    const missing = runCli([
      "--exceptions",
      join(fixtureDir, "missing-field.yaml"),
      "--image",
      "api",
      "--today",
      TODAY,
    ]);
    assert.equal(missing.status, 1);
    assert.match(missing.stderr, /missing field expiry/);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

