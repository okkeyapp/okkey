/**
 * Discovers web + email locale JSON files and writes generated TypeScript modules.
 * Adding a locale: drop `locales/web/<code>.json` + `locales/email/<code>.json`
 * (and optional `locales/manifest.json` entry). No hand-edited locale unions.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const pkgRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const localesRoot = path.join(pkgRoot, "src", "locales");
const webDir = path.join(localesRoot, "web");
const emailDir = path.join(localesRoot, "email");
const manifestPath = path.join(localesRoot, "manifest.json");

const DEFAULT_THRESHOLD = 80;
const DEFAULT_FALLBACK = "en";

function listLocaleCodes(dir) {
  return fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(".json"))
    .map((f) => path.basename(f, ".json"))
    .sort();
}

function loadJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function keyCoveragePercent(localeBundle, referenceBundle) {
  const refKeys = Object.keys(referenceBundle);
  if (refKeys.length === 0) {
    return 100;
  }
  let present = 0;
  for (const key of refKeys) {
    if (Object.prototype.hasOwnProperty.call(localeBundle, key)) {
      present += 1;
    }
  }
  return Math.floor((present / refKeys.length) * 100);
}

function writeWebBundles(codes) {
  const outFile = path.join(pkgRoot, "src", "web-bundles.gen.ts");
  const lines = [
    "// Generated by scripts/gen-locale-bundles.mjs — do not edit by hand.",
    "",
    ...codes.map((code) => `import ${code} from "./locales/web/${code}.json" with { type: "json" };`),
    "",
    "export const webBundles = {",
    ...codes.map((code) => `  ${code},`),
    "} as const;",
    "",
    "export type WebLocale = keyof typeof webBundles;",
    "",
    "export const WEB_LOCALES = Object.keys(webBundles) as WebLocale[];",
    "",
  ];
  fs.writeFileSync(outFile, `${lines.join("\n")}\n`);
}

function writeEmailBundles(codes) {
  const outFile = path.join(pkgRoot, "src", "email-bundles.gen.ts");
  const lines = [
    "// Generated by scripts/gen-locale-bundles.mjs — do not edit by hand.",
    "",
    ...codes.map(
      (code) => `import ${code} from "./locales/email/${code}.json" with { type: "json" };`,
    ),
    "",
    "export const emailBundles = {",
    ...codes.map((code) => `  ${code},`),
    "} as const;",
    "",
    "export type EmailLocale = keyof typeof emailBundles;",
    "",
    "export const EMAIL_LOCALES = Object.keys(emailBundles) as EmailLocale[];",
    "",
  ];
  fs.writeFileSync(outFile, `${lines.join("\n")}\n`);
}

/**
 * Shared AppLocale registry: same codes for web + email, readiness, Intl / dir / docs meta.
 */
function writeLocaleRegistry({
  codes,
  fallback,
  defaults,
  threshold,
  localeMeta,
  webCoverage,
  emailCoverage,
  readyLocales,
}) {
  const outFile = path.join(pkgRoot, "src", "locale-registry.gen.ts");
  const metaEntries = codes.map((code) => {
    const m = localeMeta[code];
    return `  ${code}: {
    intl: ${JSON.stringify(m.intl)},
    dir: ${JSON.stringify(m.dir)},
    dateFns: ${JSON.stringify(m.dateFns)},
    docsPathPrefix: ${JSON.stringify(m.docsPathPrefix)},
    yearMonthOrder: ${JSON.stringify(m.yearMonthOrder)},
    ready: ${m.ready ? "true" : "false"},
    webCoveragePercent: ${webCoverage[code]},
    emailCoveragePercent: ${emailCoverage[code]},
  }`;
  });

  const lines = [
    "// Generated by scripts/gen-locale-bundles.mjs — do not edit by hand.",
    "",
    'import type { EmailLocale } from "./email-bundles.gen.js";',
    'import type { WebLocale } from "./web-bundles.gen.js";',
    "",
    "/** Shared locale code for web UI and email (same discovered set). */",
    "export type AppLocale = WebLocale & EmailLocale;",
    "",
    `export const APP_LOCALES = ${JSON.stringify(codes)} as readonly AppLocale[];`,
    "",
    `export const FALLBACK_LOCALE = ${JSON.stringify(fallback)} as AppLocale;`,
    "",
    `export const LOCALE_READINESS_THRESHOLD_PERCENT = ${threshold};`,
    "",
    "export const LOCALE_DEFAULTS = {",
    `  fallback: ${JSON.stringify(defaults.fallback)} as AppLocale,`,
    `  web: ${JSON.stringify(defaults.web)} as AppLocale,`,
    `  email: ${JSON.stringify(defaults.email)} as AppLocale,`,
    `  extensionUi: ${JSON.stringify(defaults.extensionUi)} as AppLocale,`,
    `  storePackage: ${JSON.stringify(defaults.storePackage)} as AppLocale,`,
    "} as const;",
    "",
    "export type LocaleDir = \"ltr\" | \"rtl\";",
    "",
    "export type YearMonthOrder = \"month-year\" | \"year-month\";",
    "",
    "export type LocaleMeta = {",
    "  intl: string;",
    "  dir: LocaleDir;",
    "  dateFns: string;",
    "  docsPathPrefix: string;",
    "  yearMonthOrder: YearMonthOrder;",
    "  ready: boolean;",
    "  webCoveragePercent: number;",
    "  emailCoveragePercent: number;",
    "};",
    "",
    "export const LOCALE_META: Record<AppLocale, LocaleMeta> = {",
    metaEntries.join(",\n"),
    "};",
    "",
    "/** Locales shown in language switchers (ready flag + coverage ≥ threshold). */",
    `export const READY_LOCALES = ${JSON.stringify(readyLocales)} as readonly AppLocale[];`,
    "",
  ];
  fs.writeFileSync(outFile, `${lines.join("\n")}\n`);
}

function resolveMetaEntry(code, rawLocales, fallbackMeta) {
  const raw = rawLocales[code] ?? {};
  return {
    intl: typeof raw.intl === "string" ? raw.intl : fallbackMeta.intl,
    dir: raw.dir === "rtl" ? "rtl" : "ltr",
    dateFns: typeof raw.dateFns === "string" ? raw.dateFns : fallbackMeta.dateFns,
    docsPathPrefix:
      typeof raw.docsPathPrefix === "string" ? raw.docsPathPrefix : fallbackMeta.docsPathPrefix,
    yearMonthOrder: raw.yearMonthOrder === "year-month" ? "year-month" : "month-year",
    // Explicit false blocks readiness; otherwise coverage decides (see below).
    readyFlag: raw.ready !== false,
    explicitReady: raw.ready === true,
  };
}

function main() {
  const webCodes = listLocaleCodes(webDir);
  const emailCodes = listLocaleCodes(emailDir);

  if (webCodes.length === 0) {
    throw new Error(`No JSON locale files in ${webDir}`);
  }
  if (emailCodes.length === 0) {
    throw new Error(`No JSON locale files in ${emailDir}`);
  }

  const webSet = new Set(webCodes);
  const emailSet = new Set(emailCodes);
  const onlyWeb = webCodes.filter((c) => !emailSet.has(c));
  const onlyEmail = emailCodes.filter((c) => !webSet.has(c));
  if (onlyWeb.length > 0 || onlyEmail.length > 0) {
    throw new Error(
      `Web and email locale sets must match. onlyWeb=${onlyWeb.join(",") || "∅"} onlyEmail=${onlyEmail.join(",") || "∅"}`,
    );
  }

  const codes = webCodes;
  const manifest = fs.existsSync(manifestPath) ? loadJson(manifestPath) : {};
  const threshold =
    typeof manifest.readinessThresholdPercent === "number"
      ? manifest.readinessThresholdPercent
      : DEFAULT_THRESHOLD;
  const defaults = {
    fallback: manifest.defaults?.fallback ?? DEFAULT_FALLBACK,
    web: manifest.defaults?.web ?? DEFAULT_FALLBACK,
    email: manifest.defaults?.email ?? DEFAULT_FALLBACK,
    extensionUi: manifest.defaults?.extensionUi ?? "ru",
    storePackage: manifest.defaults?.storePackage ?? DEFAULT_FALLBACK,
  };
  const fallback = defaults.fallback;
  if (!codes.includes(fallback)) {
    throw new Error(`Fallback locale "${fallback}" is missing from discovered locales`);
  }
  for (const key of ["web", "email", "extensionUi", "storePackage"]) {
    if (!codes.includes(defaults[key])) {
      throw new Error(`Default locale defaults.${key}="${defaults[key]}" is not a discovered locale`);
    }
  }

  const webEn = loadJson(path.join(webDir, `${fallback}.json`));
  const emailEn = loadJson(path.join(emailDir, `${fallback}.json`));
  const rawLocales = manifest.locales && typeof manifest.locales === "object" ? manifest.locales : {};

  const fallbackMeta = {
    intl: fallback === "en" ? "en-US" : fallback,
    dateFns: fallback === "en" ? "enUS" : fallback,
    docsPathPrefix: fallback === "en" ? "/en" : "",
  };

  const localeMeta = {};
  const webCoverage = {};
  const emailCoverage = {};
  const readyLocales = [];

  for (const code of codes) {
    const webBundle = loadJson(path.join(webDir, `${code}.json`));
    const emailBundle = loadJson(path.join(emailDir, `${code}.json`));
    webCoverage[code] = keyCoveragePercent(webBundle, webEn);
    emailCoverage[code] = keyCoveragePercent(emailBundle, emailEn);
    const resolved = resolveMetaEntry(code, rawLocales, {
      ...fallbackMeta,
      intl: code === "en" ? "en-US" : code === "ru" ? "ru-RU" : code,
      dateFns: code === "en" ? "enUS" : code,
      docsPathPrefix: code === "en" ? "/en" : "",
      yearMonthOrder: code === "ru" ? "year-month" : "month-year",
    });
    const coverageOk =
      webCoverage[code] >= threshold && emailCoverage[code] >= threshold;
    const ready = resolved.readyFlag && coverageOk;
    localeMeta[code] = {
      intl: resolved.intl,
      dir: resolved.dir,
      dateFns: resolved.dateFns,
      docsPathPrefix: resolved.docsPathPrefix,
      yearMonthOrder: resolved.yearMonthOrder,
      ready,
    };
    if (ready) {
      readyLocales.push(code);
    }
  }

  if (!readyLocales.includes(fallback)) {
    throw new Error(`Fallback locale "${fallback}" must be ready (coverage ≥ ${threshold}%)`);
  }

  writeWebBundles(codes);
  writeEmailBundles(codes);
  writeLocaleRegistry({
    codes,
    fallback,
    defaults,
    threshold,
    localeMeta,
    webCoverage,
    emailCoverage,
    readyLocales,
  });
}

main();
