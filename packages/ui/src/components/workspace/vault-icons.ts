export type VaultIconEmoji = (typeof VAULT_ICON_EMOJIS)[number];

export const DEFAULT_PERSONAL_VAULT_ICON: VaultIconEmoji = "🏠";
export const DEFAULT_SHARED_VAULT_ICON: VaultIconEmoji = "💼";

export function normalizeVaultIcon(icon: string | null | undefined, fallback: string): string {
  const trimmed = icon?.trim() ?? "";
  return trimmed.length > 0 ? trimmed : fallback;
}

export function vaultDisplayIcon(vault: {
  icon?: string | null;
  isPersonal: boolean;
}): string {
  return normalizeVaultIcon(
    vault.icon,
    vault.isPersonal ? DEFAULT_PERSONAL_VAULT_ICON : DEFAULT_SHARED_VAULT_ICON,
  );
}
