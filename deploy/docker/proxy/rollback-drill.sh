#!/usr/bin/env bash
# Q-Day #3 q3-6 — exercise 6.19 rollback checklist once against in-tree artifacts.
#
# Approved emergency path (runbook § Rollback): enable the pre-approved classical
# compatibility profile on isolated hosts (OKKEY_COMPAT_*), keep HTTPS, then
# restore hybrid-only default (OKKEY_COMPAT_ENABLED=0). Never merge classical
# curves onto the strict default route.
#
# Usage:
#   ./rollback-drill.sh
#   STRICT_HOST=app.example.com COMPAT_HOST=compat-app.example.com ./rollback-drill.sh
#
# Without live DNS / Docker this is a dry-run of config switch + restore + static
# policy re-verify. Pass STRICT_HOST (+ optional COMPAT_HOST) to print the live
# verify command pack (OpenSSL ≥ 3.5 client required for hybrid group).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")" && pwd)"
EDGE_POLICY="${ROOT}/../../saas/edge/policy-review.sh"
STRICT_TMPL="${ROOT}/nginx/conf.d/okkey.conf.template"
COMPAT_TMPL="${ROOT}/nginx/conf.d/okkey-compat.conf.template"
COMPAT_ENV="${ROOT}/compat.env.example"
ENTRY="${ROOT}/nginx/docker-entrypoint.sh"

OWNER="${OKKEY_DRILL_OWNER:-q3-6-agent}"
TS_UTC="$(date -u +%Y-%m-%dT%H:%MZ)"
SUNSET_DRILL="$(date -u -d '+30 days' +%Y-%m-%d 2>/dev/null || date -u -v+30d +%Y-%m-%d 2>/dev/null || echo '2099-12-31')"

fail() { echo "ERROR: $*" >&2; exit 1; }
step() { echo; echo "==> $*"; }

step "1) Drill announced (checklist D — incident channel substitute)"
echo "rollback-drill: DECLARED at ${TS_UTC} UTC by ${OWNER}"
echo "rollback-drill: trigger=simulated_handshake_lockout_slo (non-prod drill)"
echo "rollback-drill: scope=self-host proxy + SaaS edge manifests (no live stage DNS required for dry-run)"

step "2) Pre-approved compatibility profile present"
[[ -f "${COMPAT_TMPL}" ]] || fail "missing compat template ${COMPAT_TMPL}"
[[ -f "${COMPAT_ENV}" ]] || fail "missing ${COMPAT_ENV}"
[[ -x "${ENTRY}" ]] || fail "entrypoint missing/not executable"
grep -q 'ssl_ecdh_curve X25519;' "${COMPAT_TMPL}" \
  || fail "compat profile must be classical X25519"
grep -Eq 'listen[[:space:]]+\$\{OKKEY_COMPAT_HTTPS_PORT\}[[:space:]]+ssl' "${COMPAT_TMPL}" \
  || fail "compat profile must remain HTTPS on dedicated OKKEY_COMPAT_HTTPS_PORT (not shared :443)"
if grep -E '^[[:space:]]*listen' "${COMPAT_TMPL}" | grep -Eq '[[:space:]]443[[:space:]]'; then
  fail "compat must not listen on 443 (TLS 1.3 key_share isolation)"
fi
grep -q 'compat-fullchain.pem' "${COMPAT_TMPL}" \
  || fail "compat profile must use dedicated compat-fullchain.pem"
grep -q 'OKKEY_COMPAT_ENABLED' "${ENTRY}" || fail "entrypoint must gate compat enable"
echo "OK: pre-approved compat artifacts in tree"

step "3) Switch TO compatibility profile (config dry-run — do not mutate committed defaults)"
# Illustrative emergency env (operator would merge into install .env / stage.env).
ROLLBACK_ENV="$(mktemp)"
RESTORE_ENV="$(mktemp)"
trap 'rm -f "${ROLLBACK_ENV}" "${RESTORE_ENV}"' EXIT

cat > "${ROLLBACK_ENV}" <<EOF
# Generated by rollback-drill.sh at ${TS_UTC} — DO NOT COMMIT
# Emergency: enable isolated classical listeners (HTTPS on dedicated port).
OKKEY_COMPAT_ENABLED=1
OKKEY_COMPAT_WEB_HOST=compat-app.example.com
OKKEY_COMPAT_API_HOST=compat-api.example.com
OKKEY_COMPAT_HTTPS_PORT=8443
OKKEY_COMPAT_SUNSET=${SUNSET_DRILL}
OKKEY_COMPAT_OWNER=${OWNER}
EOF

cat > "${RESTORE_ENV}" <<EOF
# Generated by rollback-drill.sh at ${TS_UTC} — DO NOT COMMIT
# Restore: hybrid-only default; compat off.
OKKEY_COMPAT_ENABLED=0
EOF

echo "--- rollback action (enable compat) ---"
cat "${ROLLBACK_ENV}"
grep -Eq '^OKKEY_COMPAT_ENABLED=1$' "${ROLLBACK_ENV}" || fail "rollback env must enable compat"
grep -Eq '^OKKEY_COMPAT_SUNSET=' "${ROLLBACK_ENV}" || fail "rollback env must set sunset"
grep -Eq '^OKKEY_COMPAT_OWNER=' "${ROLLBACK_ENV}" || fail "rollback env must set owner"
# Isolation: drill hosts must not equal documented default example hosts
grep -Eq 'compat-app\.example\.com' "${ROLLBACK_ENV}" || fail "rollback web host not isolated"
echo "OK: rollback action = enable time-boxed isolated compat (not classical on default route)"

step "4) HTTPS-only + default hybrid guardrails still hold during rollback"
grep -q 'ssl_protocols TLSv1.3;' "${STRICT_TMPL}" \
  || fail "strict default must stay TLSv1.3 during rollback"
grep -q 'ssl_ecdh_curve X25519MLKEM768;' "${STRICT_TMPL}" \
  || fail "strict default must stay X25519MLKEM768 during rollback"
if grep -Eiq 'ssl_protocols[[:space:]]+.*TLSv1\.[012]' "${STRICT_TMPL}"; then
  fail "strict default must not enable TLS ≤ 1.2"
fi
# Compat must not bind default host vars
if grep -E 'server_name[[:space:]]+\$\{OKKEY_(WEB|API)_HOST\}' "${COMPAT_TMPL}"; then
  fail "compat must not use default OKKEY_WEB_HOST/API_HOST"
fi
# HTTP→HTTPS redirect remains on default hosts
grep -q 'return 301 https://' "${STRICT_TMPL}" \
  || fail "strict template must keep HTTP→HTTPS redirect"
echo "OK: HTTPS posture + hybrid default route unchanged; classical only on compat hosts"

step "5) Restore hybrid default (compat off)"
echo "--- restore action ---"
cat "${RESTORE_ENV}"
grep -Eq '^OKKEY_COMPAT_ENABLED=0$' "${RESTORE_ENV}" || fail "restore must set ENABLED=0"
grep -q 'OKKEY_COMPAT_ENABLED=0' "${COMPAT_ENV}" \
  || fail "committed compat.env.example must default ENABLED=0 (restore baseline)"
echo "OK: restore = OKKEY_COMPAT_ENABLED=0 (committed default)"

step "6) Re-verify static policy (evidence re-check)"
"${ROOT}/policy-compat.sh"
[[ -x "${EDGE_POLICY}" ]] || fail "missing SaaS policy-review.sh"
"${EDGE_POLICY}"
echo "OK: static policy PASS after restore"

step "7) Live verify command pack (optional — deferred without DNS/Docker)"
if [[ -n "${STRICT_HOST:-}" ]]; then
  echo "Live strict host provided: ${STRICT_HOST}"
  echo "  ${ROOT}/verify-tls.sh ${STRICT_HOST} 443"
  if [[ -n "${COMPAT_HOST:-}" ]]; then
    echo "  ${ROOT}/verify-compat.sh ${STRICT_HOST} 443 ${COMPAT_HOST} 443"
  else
    echo "  (set COMPAT_HOST to also exercise classical-on-compat after enable)"
  fi
  echo "NOTE: this drill does not mutate a live edge; operator applies rollback/restore env then re-runs verify."
else
  echo "STRICT_HOST unset — live s_client paste deferred (same as q3-5: no stage DNS / no Docker here)."
  echo "When available:"
  echo "  STRICT_HOST=app.stage.okkey.app COMPAT_HOST=compat-app.stage.okkey.app ./rollback-drill.sh"
fi

step "8) Post-drill action item"
echo "ticket: re-enable hybrid-only default (already restored in dry-run); keep compat sunset+owner if live enable was used"
echo "owner: ${OWNER}"
echo "deadline: before next PQ TLS canary / parent q3-7"

echo
echo "PASS: rollback checklist D exercised (dry-run) at ${TS_UTC} by ${OWNER}"
echo "PASS: switch→compat artifacts validated; HTTPS+hybrid default intact; restore→ENABLED=0; policy re-verify OK"
