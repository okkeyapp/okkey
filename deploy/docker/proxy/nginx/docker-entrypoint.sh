#!/bin/sh
set -eu

: "${OKKEY_WEB_HOST:=app.example.com}"
: "${OKKEY_API_HOST:=api.example.com}"
: "${OKKEY_WEB_UPSTREAM:=web:80}"
: "${OKKEY_API_UPSTREAM:=api:4000}"
: "${OKKEY_COMPAT_ENABLED:=0}"

export OKKEY_WEB_HOST OKKEY_API_HOST OKKEY_WEB_UPSTREAM OKKEY_API_UPSTREAM

envsubst '${OKKEY_WEB_HOST} ${OKKEY_API_HOST} ${OKKEY_WEB_UPSTREAM} ${OKKEY_API_UPSTREAM}' \
  < /etc/nginx/templates/okkey.conf.template \
  > /etc/nginx/conf.d/okkey.conf

# Default: no compat listeners (empty include keeps nginx -t happy if referenced nowhere).
rm -f /etc/nginx/conf.d/okkey-compat.conf
printf '# compat allowlist unused (compat disabled)\n' > /etc/nginx/conf.d/compat-allow.inc

case "${OKKEY_COMPAT_ENABLED}" in
  1|true|TRUE|yes|YES)
    : "${OKKEY_COMPAT_WEB_HOST:?OKKEY_COMPAT_ENABLED requires OKKEY_COMPAT_WEB_HOST}"
    : "${OKKEY_COMPAT_API_HOST:?OKKEY_COMPAT_ENABLED requires OKKEY_COMPAT_API_HOST}"
    : "${OKKEY_COMPAT_SUNSET:?OKKEY_COMPAT_ENABLED requires OKKEY_COMPAT_SUNSET (YYYY-MM-DD)}"
    : "${OKKEY_COMPAT_OWNER:?OKKEY_COMPAT_ENABLED requires OKKEY_COMPAT_OWNER}"

    case "${OKKEY_COMPAT_SUNSET}" in
      [0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]) ;;
      *)
        echo "okkey-proxy: OKKEY_COMPAT_SUNSET must be YYYY-MM-DD (got: ${OKKEY_COMPAT_SUNSET})" >&2
        exit 1
        ;;
    esac

    TODAY="$(date -u +%Y-%m-%d)"
    if [ "${OKKEY_COMPAT_SUNSET}" '<' "${TODAY}" ]; then
      echo "okkey-proxy: compat sunset ${OKKEY_COMPAT_SUNSET} is in the past (today ${TODAY} UTC) — refuse enable" >&2
      exit 1
    fi

    if [ "${OKKEY_COMPAT_WEB_HOST}" = "${OKKEY_WEB_HOST}" ] \
      || [ "${OKKEY_COMPAT_API_HOST}" = "${OKKEY_API_HOST}" ] \
      || [ "${OKKEY_COMPAT_WEB_HOST}" = "${OKKEY_API_HOST}" ] \
      || [ "${OKKEY_COMPAT_API_HOST}" = "${OKKEY_WEB_HOST}" ]; then
      echo "okkey-proxy: compat hosts must be isolated from default strict hosts" >&2
      echo "okkey-proxy: default web=${OKKEY_WEB_HOST} api=${OKKEY_API_HOST}" >&2
      echo "okkey-proxy: compat  web=${OKKEY_COMPAT_WEB_HOST} api=${OKKEY_COMPAT_API_HOST}" >&2
      exit 1
    fi

    if [ "${OKKEY_COMPAT_WEB_HOST}" = "${OKKEY_COMPAT_API_HOST}" ]; then
      echo "okkey-proxy: OKKEY_COMPAT_WEB_HOST and OKKEY_COMPAT_API_HOST must differ" >&2
      exit 1
    fi

    # Optional CIDR allowlist (comma-separated). Empty → open (still isolated by hostname).
    {
      echo "# generated by docker-entrypoint.sh — do not edit"
      if [ -n "${OKKEY_COMPAT_ALLOW_CIDRS:-}" ]; then
        OLD_IFS=$IFS
        IFS=,
        for cidr in ${OKKEY_COMPAT_ALLOW_CIDRS}; do
          cidr=$(echo "${cidr}" | tr -d ' ')
          [ -n "${cidr}" ] || continue
          echo "allow ${cidr};"
        done
        IFS=$OLD_IFS
        echo "deny all;"
      else
        echo "# no OKKEY_COMPAT_ALLOW_CIDRS — hostname isolation only"
      fi
    } > /etc/nginx/conf.d/compat-allow.inc

    export OKKEY_COMPAT_WEB_HOST OKKEY_COMPAT_API_HOST OKKEY_COMPAT_SUNSET
    envsubst '${OKKEY_COMPAT_WEB_HOST} ${OKKEY_COMPAT_API_HOST} ${OKKEY_COMPAT_SUNSET} ${OKKEY_WEB_UPSTREAM} ${OKKEY_API_UPSTREAM}' \
      < /etc/nginx/templates/okkey-compat.conf.template \
      > /etc/nginx/conf.d/okkey-compat.conf

    echo "okkey-proxy: compat listeners ENABLED until ${OKKEY_COMPAT_SUNSET} (owner=${OKKEY_COMPAT_OWNER})"
    echo "okkey-proxy: compat web=${OKKEY_COMPAT_WEB_HOST} api=${OKKEY_COMPAT_API_HOST}"
    ;;
  0|false|FALSE|no|NO|'')
    echo "okkey-proxy: compat listeners disabled (OKKEY_COMPAT_ENABLED=${OKKEY_COMPAT_ENABLED:-0})"
    ;;
  *)
    echo "okkey-proxy: OKKEY_COMPAT_ENABLED must be 0 or 1 (got: ${OKKEY_COMPAT_ENABLED})" >&2
    exit 1
    ;;
esac

if [ ! -f /etc/nginx/certs/fullchain.pem ] || [ ! -f /etc/nginx/certs/privkey.pem ]; then
  echo "okkey-proxy: missing /etc/nginx/certs/{fullchain,privkey}.pem" >&2
  echo "okkey-proxy: run scripts/gen-self-signed.sh or mount real certificates" >&2
  exit 1
fi

# Fail fast if the linked OpenSSL cannot offer the hybrid group.
if ! openssl list -tls-groups 2>/dev/null | grep -q 'X25519MLKEM768'; then
  echo "okkey-proxy: OpenSSL at $(command -v openssl) does not list X25519MLKEM768" >&2
  echo "okkey-proxy: need OpenSSL ≥ 3.5 (got: $(openssl version))" >&2
  exit 1
fi

nginx -t
exec "$@"
