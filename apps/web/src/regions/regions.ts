export type RegionCode = (typeof REGION_CODES)[number];

export function isRegionCode(value: string): value is RegionCode {
  return (REGION_CODES as readonly string[]).includes(value);
}

export function normalizeRegionCode(value: string | null | undefined): RegionCode | null {
  if (!value) {
    return null;
  }
  const normalized = value.trim().toUpperCase();
  return isRegionCode(normalized) ? normalized : null;
}

export function detectBrowserRegion(): RegionCode {
  if (typeof navigator === "undefined") {
    return DEFAULT_REGION_CODE;
  }
  const languages = navigator.languages?.length ? navigator.languages : [navigator.language];
  for (const language of languages) {
    const region = normalizeRegionCode(language.split("-").at(-1));
    if (region && region !== language.toUpperCase()) {
      return region;
    }
  }
  return DEFAULT_REGION_CODE;
}

export function formatRegionName(region: RegionCode, locale: WebLocale): string {
  try {
    return new Intl.DisplayNames([locale], { type: "region" }).of(region) ?? region;
  } catch {
    return region;
  }
}
